// Funciones de utilidad

// Obtener anime por ID
export const getAnimeById = (id: string): AnimeData | undefined => {
  return animeDatabase.find(anime => anime.id === id);
};

// Obtener animes por tipo
export const getAnimeByType = (type: AnimeData['type']): AnimeData[] => {
  return animeDatabase.filter(anime => anime.type === type);
};

// Obtener todos los animes
export const getAllAnime = (): AnimeData[] => {
  return animeDatabase;
};

// Agregar nuevo anime
export const addAnime = (anime: AnimeData): void => {
  if (!anime.id || !anime.title || !anime.image) {
    throw new Error('Faltan datos requeridos para el anime');
  }
  animeDatabase.push(anime);
};

// Actualizar anime existente
export const updateAnime = (id: string, updates: Partial<AnimeData>): void => {
  const index = animeDatabase.findIndex(anime => anime.id === id);
  if (index !== -1) {
    animeDatabase[index] = { ...animeDatabase[index], ...updates };
  }
};

// Eliminar anime
export const deleteAnime = (id: string): void => {
  const index = animeDatabase.findIndex(anime => anime.id === id);
  if (index !== -1) {
    animeDatabase.splice(index, 1);
  }
};

// Filtrar animes por múltiples criterios
export const filterAnime = (filters: {
  type?: string;
  genre?: string;
  year?: number;
  status?: string;
  search?: string;
}): AnimeData[] => {
  return animeDatabase.filter(anime => {
    let matches = true;
    
    if (filters.type && anime.type !== filters.type) matches = false;
    if (filters.genre && !anime.genres.includes(filters.genre)) matches = false;
    if (filters.year && anime.year !== filters.year) matches = false;
    if (filters.status && anime.status !== filters.status) matches = false;
    if (filters.search) {
      const searchLower = filters.search.toLowerCase();
      const matchesSearch = 
        anime.title.toLowerCase().includes(searchLower) ||
        anime.synopsis.toLowerCase().includes(searchLower) ||
        anime.genres.some(genre => genre.toLowerCase().includes(searchLower));
      if (!matchesSearch) matches = false;
    }
    
    return matches;
  });
};